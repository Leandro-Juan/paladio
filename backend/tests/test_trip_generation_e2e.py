async def execute_frontend_trip_e2e(
    origin_city: str,
    destination_city: str,
    duration_days: int,
    prompt: str,
    budget_usd: float = 1500.0,
    meals: list[dict] | None = None,
    start_date: str | None = None,
    end_date: str | None = None,
    user_id: str = DEFAULT_USER_ID,
    ws_url: str = DEFAULT_WS_URL,
    api_url: str = DEFAULT_API_URL,
    timeout_seconds: float = 360.0,
) -> dict:
    """
    Executes the exact same workflow as the Paladio frontend:
    1. Derives dates (start_date + duration_days).
    2. Builds message payload identical to TripPreparationForm.tsx (test_mode: true).
    3. Connects to WebSocket /ws/stream with JWT token.
    4. Emits 'attach' frame, then 'chat' action.
    5. Listens to telemetry events, auto-resuming VERIFICATION_REQUIRED and TRIP_OVERLAP_WARNING.
    6. Extracts the generated itinerary from EVALUATING_ROUTES.
    7. Persists the generated itinerary via POST /trips/ (matching handleSaveTrip in engine/page.tsx).
    8. Validates roundtrip retrieval via GET /trips/{id}.
    """
    today = datetime.date.today()
    if not start_date:
        start_d = today + datetime.timedelta(days=7)
        start_date = start_d.strftime("%Y-%m-%d")
    else:
        start_d = datetime.date.fromisoformat(start_date.split("T")[0])

    if not end_date:
        end_d = start_d + datetime.timedelta(days=duration_days)
        end_date = end_d.strftime("%Y-%m-%d")

    active_meals = meals if meals is not None else DEFAULT_MEALS
    from app.core.security import create_access_token

    token = create_access_token(subject=user_id)
    thread_id = f"paladio_{int(time.time())}_{uuid.uuid4().hex[:6]}"

    # Exact payload generated by TripPreparationForm.tsx + handlePrepSubmit
    chat_payload = {
        "action": "chat",
        "message": prompt,
        "thread_id": thread_id,
        "token": token,
        "test_mode": True,
        "origin_city": origin_city.strip(),
        "destination_city": destination_city.strip(),
        "start_date": start_date,
        "end_date": end_date,
        "budget_usd": float(budget_usd),
        "meals": active_meals,
        "manual_constraints": {
            "budget_usd": float(budget_usd),
            "meals": active_meals,
        },
    }

    ws_target_url = f"{ws_url}?token={token}"
    events_received: list[dict] = []
    latest_itinerary: dict | None = None
    inference_complete = False

    logger.info(
        f"[E2E] Starting Trip Generation: {origin_city} -> {destination_city} ({duration_days} days)"
    )
    logger.info(f"[E2E] Connecting to WebSocket: {ws_target_url}")

    start_time = time.time()
    reconnect_attempts = 0
    max_reconnects = 3

    while not inference_complete and (time.time() - start_time < timeout_seconds):
        try:
            async with websockets.connect(
                ws_target_url, ping_timeout=None, ping_interval=None
            ) as ws:
                # Step 4a: Send attach frame matching SocketContext.tsx
                attach_msg = json.dumps({"action": "attach", "thread_id": thread_id})
                await ws.send(attach_msg)

                # Step 4b: Send initial chat message on first connect
                if not events_received:
                    await ws.send(json.dumps(chat_payload))
                    logger.info(f"[E2E] Submitted chat payload for thread {thread_id}")

                while time.time() - start_time < timeout_seconds:
                    try:
                        raw_msg = await asyncio.wait_for(ws.recv(), timeout=30.0)
                    except asyncio.TimeoutError:
                        logger.info(
                            f"[E2E] Heartbeat: waiting on solver... (elapsed: {int(time.time() - start_time)}s)"
                        )
                        continue

                    try:
                        msg_json = json.loads(raw_msg)
                    except Exception:
                        continue

                    event = msg_json.get("event")
                    status = msg_json.get("status")
                    events_received.append(msg_json)

                    logger.info(f"[E2E EVENT] {event} (status: {status})")

                    # Step 5a: Handle Human-In-The-Loop Verification (Matches 'Confirm & Proceed' button in engine/page.tsx)
                    if event == "VERIFICATION_REQUIRED":
                        logger.info(
                            "[E2E] VERIFICATION_REQUIRED received. Resuming with approved=True..."
                        )
                        resume_payload = {
                            "action": "resume",
                            "thread_id": thread_id,
                            "data": {"approved": True, "proceed": True},
                        }
                        await ws.send(json.dumps(resume_payload))

                    # Step 5b: Handle Schedule Overlap Warning (Matches 'Proceed with Overlap' button)
                    elif event == "TRIP_OVERLAP_WARNING":
                        logger.info(
                            "[E2E] TRIP_OVERLAP_WARNING received. Resuming with proceed_with_overlap=True..."
                        )
                        resume_payload = {
                            "action": "resume",
                            "thread_id": thread_id,
                            "data": {"proceed_with_overlap": True},
                        }
                        await ws.send(json.dumps(resume_payload))

                    # Step 5c: Capture Itinerary Output from EVALUATING_ROUTES
                    elif event == "EVALUATING_ROUTES":
                        data = msg_json.get("data")
                        if isinstance(data, dict) and "days" in data:
                            latest_itinerary = data
                            logger.info(
                                f"[E2E] Captured optimized itinerary with {len(data['days'])} days!"
                            )

                    # Step 5d: Inference Complete
                    elif event == "DONE":
                        logger.info("[E2E] Inference cycle complete (DONE received).")
                        inference_complete = True
                        break

                    elif event == "GUARDRAILS_ABORTED":
                        abort_data = msg_json.get("data")
                        logger.error(f"[E2E] Guardrails aborted trip: {abort_data}")
                        raise RuntimeError(f"Trip aborted by guardrails: {abort_data}")

                    elif event == "ERROR":
                        err_msg = msg_json.get("status", "Unknown engine error")
                        raise RuntimeError(f"Engine emitted error: {err_msg}")

        except (
            websockets.exceptions.ConnectionClosedError,
            websockets.exceptions.ConnectionClosedOK,
        ) as e:
            if inference_complete or (latest_itinerary and e.code == 1000):
                break
            reconnect_attempts += 1
            if reconnect_attempts > max_reconnects:
                raise
            logger.warning(
                f"[E2E] Connection closed (code: {e.code}). Reconnecting attempt {reconnect_attempts}/{max_reconnects}..."
            )
            await asyncio.sleep(2.0)

    if not inference_complete and not latest_itinerary:
        raise TimeoutError(
            f"Trip generation did not complete within {timeout_seconds} seconds."
        )

    assert latest_itinerary is not None, "OptimizationResult itinerary was not received"
    assert "days" in latest_itinerary, "Itinerary missing 'days' structure"
    days_list = latest_itinerary["days"]
    assert (
        len(days_list) == duration_days
    ), f"Expected {duration_days} days, got {len(days_list)}"

    # Step 6: Persist Trip to Vault (Matching handleSaveTrip in engine/page.tsx & saveTrip in useTrips.ts)
    logger.info("[E2E] Saving generated itinerary to Trip Vault via POST /trips/...")
    auth_headers = {"Authorization": f"Bearer {token}"}
    save_body = {
        "destination": destination_city,
        "start_date": f"{start_date}T00:00:00.000Z",
        "end_date": f"{end_date}T00:00:00.000Z",
        "itinerary_data": latest_itinerary,
    }

    async with httpx.AsyncClient(timeout=10.0) as client:
        save_resp = await client.post(
            f"{api_url}/trips/",
            json=save_body,
            headers=auth_headers,
        )
        assert (
            save_resp.status_code == 201
        ), f"Failed to save trip: {save_resp.status_code} - {save_resp.text}"
        saved_trip = save_resp.json()
        assert "id" in saved_trip, "Saved trip missing ID"
        trip_id = saved_trip["id"]
        assert saved_trip["destination"] == destination_city
        logger.info(f"[E2E] Trip successfully saved with ID: {trip_id}")

        # Step 7: Verify Roundtrip Persistence in Database via GET /trips/{id}
        get_resp = await client.get(
            f"{api_url}/trips/{trip_id}",
            headers=auth_headers,
        )
        assert (
            get_resp.status_code == 200
        ), f"Failed to fetch saved trip: {get_resp.status_code}"
        fetched_trip = get_resp.json()
        assert fetched_trip["id"] == trip_id
        assert fetched_trip["destination"] == destination_city
        logger.info(
            f"[E2E] Verified trip persistence in database for trip ID: {trip_id}"
        )

    return {
        "trip_id": trip_id,
        "itinerary": latest_itinerary,
        "saved_trip": saved_trip,
        "events": events_received,
    }


