async def seed_poi_price_catalog(session: AsyncSession) -> int:
    """Seed initial verified admission prices into poi_price_catalog idempotently."""
    res = await session.execute(select(CityModel.id, CityModel.name))
    city_map = {name.lower(): cid for cid, name in res.all()}

    inserted = 0
    for item in INITIAL_VERIFIED_PRICES:
        city_name = item["city"].lower()
        city_id = city_map.get(city_name)
        norm_name = item["normalized_name"]
        item_id = str(
            uuid.uuid5(uuid.NAMESPACE_DNS, f"paladio:price:{city_name}:{norm_name}")
        )

        stmt = insert(PoiPriceCatalogModel).values(
            id=item_id,
            city_id=city_id,
            normalized_name=norm_name,
            wikidata_id=item.get("wikidata_id"),
            price_eur=float(item["price_eur"]),
            is_free=bool(item["is_free"]),
            source_url=item.get("source_url"),
        )
        stmt = stmt.on_conflict_do_update(
            index_elements=["id"],
            set_={
                "price_eur": stmt.excluded.price_eur,
                "is_free": stmt.excluded.is_free,
                "source_url": stmt.excluded.source_url,
                "wikidata_id": stmt.excluded.wikidata_id,
            },
        )
        await session.execute(stmt)
        inserted += 1

    await session.commit()
    logger.info("Successfully seeded %d prices into poi_price_catalog", inserted)
    return inserted
